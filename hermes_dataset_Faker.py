# KEY: simulate cross-category behaviour realistically
# Single category clients (~60%), multi-category (~40%)
# VIP and Gold clients more likely to be multi-category

def get_categories_for_client(tier):
    """Assign how many categories a client will buy from based on tier."""
    if tier == "VIP":
        n = random.choices([1, 2, 3, 4], weights=[20, 35, 30, 15])[0]
    elif tier == "Gold":
        n = random.choices([1, 2, 3],    weights=[35, 40, 25])[0]
    elif tier == "Silver":
        n = random.choices([1, 2],       weights=[60, 40])[0]
    else:  # New
        n = random.choices([1, 2],       weights=[80, 20])[0]
    return random.sample(CATEGORIES, n)

